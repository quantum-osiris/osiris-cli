#!/usr/bin/env python3
"""Generate the LaTeX number tables for the TESSERACT-MAP-02 paper.

Every number in the manuscript's tables and figures is read from the archived
analysis files in docs/phase3/ (no hand-typed results). Output: generated.tex.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
P3 = ROOT / "docs" / "phase3"

ANALYSIS = P3 / "tesseract_map_02_live_analysis.json"
SENS = P3 / "tesseract_map_02_live_sensitivity.json"
LOCK = P3 / "tesseract_map_02_live_prereg_lock.json"
USAGE = P3 / "tesseract_map_02_job_usage.json"

ARMS = [
    ("C1_STAR_FREE_OPT3", "C1", "star", "free (SABRE)", 3, 0.0171),
    ("C2_STAR_BESTPATH_OPT3", "C2", "star", "best path", 3, 0.2594),
    ("C3_STAR_BESTPATH_OPT1", "C3", "star", "best path", 1, 0.1072),
    ("C4_CHAIN_BESTPATH_OPT1", "C4", "chain", "best path", 1, 0.4048),
    ("C5_CHAIN_BESTPATH_OPT3", "C5", "chain", "best path", 3, 0.4054),
    ("C6_CHAIN_MEDPATH_OPT3", "C6", "chain", "median path", 3, 0.2783),
    ("C7_CHAIN_FREE_OPT3", "C7", "chain", "free (level-3 default)", 3, 0.4404),
]
# FakeMarrakesh predictions come from TESSERACT_MAP_02_EXPECTED_OUTCOMES.md (simulated before
# the job); they are checked below against that file so a typo cannot slip in.

CONTRAST_LABELS = {
    "routing_and_rewrite_at_opt3": ("C5$-$C2", "rewrite + SWAP removal, opt.\\ 3"),
    "routing_and_rewrite_at_opt1": ("C4$-$C3", "rewrite + SWAP removal, opt.\\ 1"),
    "qubit_selection_at_fixed_39cz": ("C5$-$C6", "best vs median path, 39 CZ"),
    "transpiler_opt3_vs_opt1_on_chain": ("C5$-$C4", "virtual-$Z$ A/A control"),
    "error_aware_path_vs_sabre_chain": ("C5$-$C7", "greedy best path vs stock layout"),
}


def sci(p: float) -> str:
    if p >= 0.01:
        return f"{p:.2f}"
    m, e = f"{p:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


def main() -> None:
    a = json.loads(ANALYSIS.read_text())
    s = json.loads(SENS.read_text())
    lock = json.loads(LOCK.read_text())
    usage = json.loads(USAGE.read_text())
    expected = (ROOT / "phase2" / "tesseract_map_02" / "TESSERACT_MAP_02_EXPECTED_OUTCOMES.md").read_text()
    for _, short, *_rest, pred in ARMS:
        assert f"`{pred:.4f} ±" in expected, (short, pred)

    out: list[str] = ["% Generated by generate_tables.py -- do not edit by hand."]
    arms = a["arm_summaries"]
    man = lock["arm_manifests"]

    # Table 1: arms
    rows = []
    for key, short, logical, layout, opt, pred in ARMS:
        r = arms[key]
        rows.append(
            f"{short} & {logical} & {layout} & {opt} & {r['twoq_gates']} & {r['depth']} & "
            f"{r['mean_classical_fidelity']:.4f} ({r['sd_classical_fidelity']:.4f}) & {pred:.4f} & "
            f"{r['mean_four_string_support']:.4f} & {100*r['max_layout_spam_err']:.1f}\\\\"
        )
    out.append("\\newcommand{\\ArmRows}{" + "\n".join(rows) + "}")

    # Table 2: contrasts (primary + secondary + Wilcoxon)
    wil = {c["contrast"]: c for c in s["wilcoxon_signed_rank_holm"]["classical_fidelity"]}
    sec = {c["contrast"]: c for c in a["paired_contrasts_four_string_support"]["contrasts"]}
    rows = []
    for c in a["paired_contrasts_classical_fidelity"]["contrasts"]:
        lab, desc = CONTRAST_LABELS[c["contrast"]]
        lo, hi = (100 * x for x in c["ci95"])
        sc = sec[c["contrast"]]
        rows.append(
            f"{lab} & {desc} & {100*c['mean_diff']:+.2f} & [{lo:+.2f}, {hi:+.2f}] & {sci(c['p_holm_adjusted'])} & "
            f"{sci(wil[c['contrast']]['wilcoxon_p_holm_adjusted'])} & {100*sc['mean_diff']:+.2f} & {sci(sc['p_holm_adjusted'])}\\\\"
        )
    out.append("\\newcommand{\\ContrastRows}{" + "\n".join(rows) + "}")

    # Figure 1: observed vs predicted
    obs = " ".join(f"({short},{arms[k]['mean_classical_fidelity']:.4f}) +- (0,{arms[k]['sd_classical_fidelity']:.4f})" for k, short, *_ in ARMS)
    prd = " ".join(f"({short},{p:.4f})" for k, short, *_r, p in ARMS)
    out.append(f"\\newcommand{{\\ObsCoords}}{{{obs}}}")
    out.append(f"\\newcommand{{\\PredCoords}}{{{prd}}}")

    # Figure 2: per-block paired differences
    def blocks(k: str) -> list[float]:
        return arms[k]["block_classical_fidelities"]

    pairs = [("C5_CHAIN_BESTPATH_OPT3", "C2_STAR_BESTPATH_OPT3", 1), ("C4_CHAIN_BESTPATH_OPT1", "C3_STAR_BESTPATH_OPT1", 2),
             ("C5_CHAIN_BESTPATH_OPT3", "C6_CHAIN_MEDPATH_OPT3", 3), ("C5_CHAIN_BESTPATH_OPT3", "C4_CHAIN_BESTPATH_OPT1", 4),
             ("C5_CHAIN_BESTPATH_OPT3", "C7_CHAIN_FREE_OPT3", 5)]
    pts = []
    for x, y, i in pairs:
        for b, (u, v) in enumerate(zip(blocks(x), blocks(y))):
            pts.append(f"({i + (b - 4.5) * 0.03:.3f},{100*(u-v):.3f})")
    out.append("\\newcommand{\\BlockDiffCoords}{" + " ".join(pts) + "}")

    # Scalars
    spam = a["per_qubit_spam_calibration"]
    path = lock["path_summary"]
    sc = {
        "JobId": a["job_id"],
        "Blocks": a["n_blocks"],
        "Shots": f"{a['shots_per_pub']:,}".replace(",", "{,}"),
        "TotalShots": f"{a['total_shots']:,}".replace(",", "{,}"),
        "NPubs": lock["total_pubs"],
        "UnionQubits": a["union_spam_qubit_count"],
        "UnionReadout": f"{100*a['union_mean_readout_error']:.2f}",
        "QFortyTwo": f"{100*spam['42']['mean_assign_err']:.1f}",
        "QFortyOne": f"{100*spam['41']['mean_assign_err']:.1f}",
        "QThirtyOne": f"{100*spam['31']['mean_assign_err']:.1f}",
        "NPaths": path["num_candidate_paths_scored"],
        "LockSha": a["prereg_lock_sha256"],
        "QpySha": a["qpy_sha256"],
        "QpuSeconds": int(usage["job_usage_seconds"]),
    }
    for k, v in sc.items():
        out.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    # membership facts used in the text, checked here rather than asserted by hand
    for q, arm in [("42", "C6_CHAIN_MEDPATH_OPT3"), ("42", "C7_CHAIN_FREE_OPT3"), ("41", "C6_CHAIN_MEDPATH_OPT3"),
                   ("41", "C7_CHAIN_FREE_OPT3"), ("31", "C5_CHAIN_BESTPATH_OPT3"), ("31", "C6_CHAIN_MEDPATH_OPT3")]:
        assert int(q) in man[arm]["final_physical_layout"], (q, arm)
    for q in ("41", "42"):
        assert int(q) not in man["C5_CHAIN_BESTPATH_OPT3"]["final_physical_layout"]
    assert 31 not in man["C7_CHAIN_FREE_OPT3"]["final_physical_layout"]

    (HERE / "generated.tex").write_text("\n".join(out) + "\n")
    print("wrote generated.tex", hashlib.sha256((HERE / "generated.tex").read_bytes()).hexdigest()[:16], sc["QpuSeconds"])


if __name__ == "__main__":
    main()
