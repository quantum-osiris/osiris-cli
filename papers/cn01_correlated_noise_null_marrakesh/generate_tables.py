#!/usr/bin/env python3
"""Generate the LaTeX number tables for the CORRELATED-NOISE-01 Stage 1 paper.

Every number in the manuscript's tables and figures is read from the archived files in
docs/phase3/ (no hand-typed results). Output: generated.tex.
"""

from __future__ import annotations

import json
from pathlib import Path

from scipy import stats

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
P3 = ROOT / "docs" / "phase3"

LOCKED = json.loads((P3 / "correlated_noise_01_live_analysis.json").read_text())
A3 = json.loads((P3 / "correlated_noise_01_live_analysis_A3.json").read_text())
VAL = json.loads((P3 / "correlated_noise_01_A3_validation.json").read_text())
USAGE = json.loads((P3 / "correlated_noise_01_job_usage.json").read_text())


def f(x: float, n: int = 2) -> str:
    return f"{x:,.{n}f}".replace(",", "{,}")


def p(x: float) -> str:
    return f"{x:.2f}"


def main() -> None:
    out = ["% Generated by generate_tables.py -- do not edit by hand."]
    t9 = stats.t.ppf(0.975, 9)

    # Mechanistic contrasts (identical in both analyses)
    names = [
        ("C_DFS_asymmetry", "$C_{\\mathrm{DFS}}$", "$\\Phi^+$ rise $-$ $\\Psi^+$ rise, 0$\\to$256\\,ns", "H2, H3 ($>0$)"),
        ("C_spectator_activation", "$C_{\\mathrm{spec}}$", "rise with spectator in $|{+}\\rangle$ $-$ in $|0\\rangle$", "H1 ($>0$)"),
        ("C_stagger_phi_256_minus_0", "$C_{\\mathrm{stagger}}$", "$\\Phi^+(256\\,\\mathrm{ns})-\\Phi^+(0)$", "--"),
        ("C_memory_dd32_minus_echo1_16us", "$C_{\\mathrm{mem}}$", "DD32 $-$ echo at 16.384\\,\\textmu s", "H3 ($>0$)"),
    ]
    mc = LOCKED["mechanistic_contrasts_10couplers_holm"]
    rows = []
    for key, sym, desc, need in names:
        c = mc[key]
        m, se = 100 * c["mean"], 100 * c["se_across_couplers"]
        rows.append(f"{sym} & {desc} & {need} & {m:+.2f} & [{m - t9*se:+.2f}, {m + t9*se:+.2f}] & {p(c['p_holm_adjusted'])}\\\\")
    out.append("\\newcommand{\\ContrastRows}{" + "\n".join(rows) + "}")
    for key, sym, *_ in names:
        assert A3["mechanistic_contrasts_holm"][key]["mean"] == mc[key]["mean"], key

    # Model selection, both analyses
    lf = LOCKED["gls_model_selection_on_training_cohort"]["fits"]
    af = A3["model_selection"]["fits"]
    local = {"H0", "H0_1f", "H3_local"}
    order = ["H0", "H0_1f", "H3_local", "H1", "H2", "H3", "Apparatus"]
    rows = []
    for m in order:
        lcol = f"{lf[m]['k_params']} & {f(lf[m]['chi2'],1)} & {f(lf[m]['bic'],1)}" if m in lf else "--- & --- & ---"
        a = af[m]
        rows.append(f"{m.replace('_', '\\_')} & {'local' if m in local else 'non-local'} & {lcol} & {a['k_params']} & {f(a['chi2'],1)} & {f(a['bic'],2)}\\\\")
    out.append("\\newcommand{\\ModelRows}{" + "\n".join(rows) + "}")

    # Validation table
    truths = [("white", "White (H0)"), ("local_1f", "Local $1/f$"), ("local_1f_ramsey_detuned", "Local $1/f$, Ramsey detuned"),
              ("local_ou", "Local OU memory"), ("correlated_h2", "Correlated Markovian (H2)"),
              ("correlated_h3_fast", "Correlated OU, fast"), ("correlated_h3_slow", "Correlated OU, slow")]
    rows = []
    summ = VAL["summary"]
    for key, lab in truths:
        s = summ[key]
        lr = s["locked"]["rates"]
        ar = s["a3"]["rates"]
        h3 = s["locked"]["selected_model_counts"].get("H3", 0) / s["n_replicates"]
        anyc = ar.get("any_nonlocal_claim", ar.get("correlated_dephasing_supported"))
        rows.append(
            f"{lab} & {s['n_replicates']} & {100*h3:.0f}\\% & {100*lr['stage2_gate']['rate']:.0f}\\% & "
            f"{100*lr['h3_memory_claim']['rate']:.0f}\\% & {100*anyc['rate']:.0f}\\% & {100*ar['correlated_dephasing_supported']['rate']:.0f}\\%\\\\"
        )
    out.append("\\newcommand{\\ValidationRows}{" + "\n".join(rows) + "}")

    # Figure: per-coupler Phi+ offset curves relative to 0 ns
    offs = [0, 16, 32, 48, 80, 160, 256]
    plots = []
    for prof in LOCKED["per_coupler_profiles"]:
        cur = prof["phi_offset_curve_raw"]
        base = cur["0ns"]
        coords = " ".join(f"({o},{100*(cur[f'{o}ns']-base):.3f})" for o in offs)
        style = "blue!60!black" if prof["role"] == "train" else "orange!80!black"
        plots.append(f"\\addplot[{style},mark=*,mark size=1pt,thin] coordinates {{{coords}}};")
    out.append("\\newcommand{\\StaggerPlots}{" + "\n".join(plots) + "}")

    ho = LOCKED["held_out_6coupler_cluster_validation_df5"]
    sc = {
        "JobId": LOCKED["job_id"],
        "Blocks": LOCKED["n_blocks"],
        "Shots": f(LOCKED["shots_per_pub"], 0),
        "TotalShots": f(LOCKED["total_circuit_shots"], 0),
        "QpuSeconds": int(USAGE.get("job_usage_seconds") or USAGE["metrics_usage"]["qpu_charge_time_seconds"]),
        "AARaw": f"{LOCKED['live_aa_sentinel_rms_pp_raw']:.2f}",
        "SFortyEight": f"{LOCKED['step_fraction_s48']:.2f}",
        "LockedDBIC": f(LOCKED["gls_model_selection_on_training_cohort"]["delta_bic_over_h0"], 0),
        "HoRmseHZero": f"{ho['mean_rmse_h0']:.3f}",
        "HoRmseHThree": f"{ho['mean_rmse_h3']:.3f}",
        "HoT": f"{ho['t_stat_h0_minus_h3_df5']:.2f}",
        "HoP": f"{ho['p_two_sided_df5']:.2f}",
        "LockSha": LOCKED["prereg_lock_sha256"],
        "QpySha": LOCKED["qpy_sha256"],
        "AmendSha": A3["analysis_amendment_sha256"],
    }
    assert LOCKED["gls_model_selection_on_training_cohort"]["selected_model"] == "H3"
    assert A3["model_selection"]["selected_model"] == "H0" and A3["decisions"]["local_noise_only"] is True
    for k, v in sc.items():
        out.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    (HERE / "generated.tex").write_text("\n".join(out) + "\n")
    print("wrote generated.tex", sc["QpuSeconds"])


if __name__ == "__main__":
    main()
