#!/usr/bin/env python3
"""Generate LaTeX tables for the TESSERACT-MAP-03 paper from the archived analysis (no hand-typed results)."""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
P3 = ROOT / "docs" / "phase3"

A = json.loads((P3 / "tesseract_map_03_live_analysis.json").read_text())
LOCK = json.loads((P3 / "tesseract_map_03_live_prereg_lock.json").read_text())
CAL = json.loads((P3 / "tesseract_map_03_prelock_calibration.json").read_text())
RAW = json.loads((P3 / "tesseract_map_03_live_raw_counts.json").read_text())
REC = json.loads((P3 / "tesseract_map_03_submission_receipt.json").read_text())
M2 = json.loads((P3 / "tesseract_map_02_live_analysis.json").read_text())

ARMS = [
    ("A1_CHAIN_BEST", "A1", "chain", "MAP-02 best path", "C5_CHAIN_BESTPATH_OPT3"),
    ("A2_CHAIN_MED", "A2", "chain", "MAP-02 median path", "C6_CHAIN_MEDPATH_OPT3"),
    ("A3_CHAIN_C7REPLAY", "A3", "chain", "MAP-02 C7 qubits", "C7_CHAIN_FREE_OPT3"),
    ("A4_CHAIN_STOCK", "A4", "chain", "stock layout today", None),
    ("A5_STAR_MED", "A5", "star", "MAP-02 median path", None),
    ("A6_STAR_BEST", "A6", "star", "MAP-02 best path", "C2_STAR_BESTPATH_OPT3"),
]
KLAB = {
    "K1_path_gap_replication": ("K1", "A1$-$A2", "path gap replication"),
    "K2_readout_share_of_path_gap": ("K2", "(A1$-$A2)$_{\\rm raw}-$(A1$-$A2)$_{\\rm mit}$", "readout share of the gap"),
    "K3_rewrite_x_path_interaction": ("K3", "(A1$-$A2)$-$(A6$-$A5)", "rewrite $\\times$ path interaction"),
    "K4_best_vs_C7_replay": ("K4", "A1$-$A3", "best path vs MAP-02 C7 qubits"),
    "K5_best_vs_stock_today": ("K5", "A1$-$A4", "best path vs today's stock layout"),
}


def sci(p: float) -> str:
    if p >= 0.01:
        return f"{p:.2f}"
    m, e = f"{p:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


def main() -> None:
    out = ["% Generated by generate_tables.py -- do not edit by hand."]
    rows = []
    m2arms = M2["arm_summaries"]
    for key, short, logical, qubits, m2key in ARMS:
        a = A["arms"][key]
        prev = f"{m2arms[m2key]['mean_classical_fidelity']:.4f}" if m2key else "--"
        rows.append(f"{short} & {logical} & {qubits} & {a['twoq_gates']} & {a['depth']} & {a['mean_fcl_raw']:.4f} ({a['sd_fcl_raw']:.4f}) & "
                    f"{a['mean_fcl_mit']:.3f} & {prev} & {100*a['max_layout_readout_err']:.1f} (q{a['worst_layout_qubit']})\\\\")
    out.append("\\newcommand{\\ArmRows}{" + "\n".join(rows) + "}")
    rows = []
    for k, (kid, form, desc) in KLAB.items():
        c = A["contrasts"][k]
        lo, hi = c["ci95_pp"]
        rows.append(f"{kid} & {form} & {desc} & {c['mean_pp']:+.2f} & [{lo:+.2f}, {hi:+.2f}] & {sci(c['p_holm'])} & {sci(c['wilcoxon_p_holm'])}\\\\")
    out.append("\\newcommand{\\ContrastRows}{" + "\n".join(rows) + "}")

    ro = A["per_qubit_readout"]
    qrows = []
    m2ro = M2["per_qubit_spam_calibration"]
    worst = sorted(ro, key=lambda q: -(ro[q]["p1_given_0"] + ro[q]["p0_given_1"]))[:6]
    for q in worst:
        e = 0.5 * (ro[q]["p1_given_0"] + ro[q]["p0_given_1"])
        prev = f"{100*m2ro[q]['mean_assign_err']:.1f}" if q in m2ro else "--"
        ibm = CAL["qubits"][q]["readout_error"]
        on = ",".join(s for key, s, *_ in ARMS if int(q) in LOCK["arm_manifests"][key]["final_physical_layout"])
        qrows.append(f"q{q} & {100*e:.1f} & {prev} & {100*ibm:.1f} & {on}\\\\")
    out.append("\\newcommand{\\QubitRows}{" + "\n".join(qrows) + "}")

    eta = A["eta_readout_share"]
    sc = {
        "JobId": A["job_id"],
        "QpuSeconds": int(round(RAW["job_usage_seconds"] or 0)),
        "EstSeconds": LOCK["estimated_qpu_seconds"],
        "SubmittedUtc": REC["submitted_utc"][:19].replace("T", " "),
        "LockedUtc": LOCK["locked_utc"][:19].replace("T", " "),
        "UnionN": len(LOCK["union_active_physical_qubits"]),
        "UnionRO": f"{100*A['union_mean_readout_err']:.2f}",
        "EtaEst": f"{eta['estimate']:.2f}",
        "EtaLo": f"{eta['bootstrap95'][0]:.2f}",
        "EtaHi": f"{eta['bootstrap95'][1]:.2f}",
    }
    c = A["contrasts"]
    sc["MitGap"] = f"{c['K1_path_gap_replication']['mean_pp'] - c['K2_readout_share_of_path_gap']['mean_pp']:+.2f}"
    sc["QFSixP"] = f"{100*ro['46']['p1_given_0']:.1f}"
    sc["QFSixQ"] = f"{100*ro['46']['p0_given_1']:.1f}"
    sc["QFSixIBM"] = f"{100*RAW['execution_time_calibration']['qubits']['46']['readout_error']:.1f}"
    sc["QTOneQ"] = f"{100*ro['31']['p0_given_1']:.1f}"
    sc["Aone"] = f"{A['arms']['A1_CHAIN_BEST']['mean_fcl_raw']:.3f}"
    sc["MtwoCfive"] = f"{M2['arm_summaries']['C5_CHAIN_BESTPATH_OPT3']['mean_classical_fidelity']:.3f}"
    for k, v in sc.items():
        out.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    (HERE / "generated.tex").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
