#!/usr/bin/env python3
"""LaTeX macros for the RO-06/RO-07 paper, read from docs/phase6 and docs/phase7 (no hand-typed results)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
A6 = json.loads((ROOT / "docs/phase6/ro06_analysis.json").read_text())
A7 = json.loads((ROOT / "docs/phase7/ro07_analysis.json").read_text())
EX = json.loads((ROOT / "docs/phase7/ro06_07_exploratory.json").read_text())
B = ["ibm_marrakesh", "ibm_fez", "ibm_kingston"]
nm = lambda b: b.replace("_", "\\_")
o = ["% Generated by generate_tables.py -- do not edit by hand."]


def mac(k, v):
    o.append(f"\\newcommand{{\\{k}}}{{{v}}}")


h1 = A6["H1_hidden_faults_per_round"]
rows = []
for b in B:
    jobs = [r["job_id"] for r in A6["rounds"][b]]
    rows.append(f"{nm(b)} & {' '.join(str(x) for x in h1[b]['counts'])} & {h1[b]['mean']:.3f} & {A6['H4_spearman_median'][b]:.2f}\\\\")
mac("HOneRows", "\n".join(rows))
hf = []
for b in B:
    for r in A6["rounds"][b]:
        for q, v in r["hidden_faults"].items():
            hf.append(f"{nm(b)} & {r['round']} & {r['time'][5:16].replace('T', ' ')} & q{q} & {100*v:.1f} & {100*r['ibm_of_hidden'][q]:.1f}\\\\")
mac("HiddenRows", "\n".join(hf))
mac("HTwoEver", A6["H2_qubits_ever_hidden"]); mac("HTwoRec", A6["H2_of_which_recovered_in_another_round"])
t = A6["H3_transition_table_[fault_r][fault_r+1]"]
mac("HThreeFF", f"{100*A6['H3_p_fault_next_given_fault']:.1f}"); mac("HThreeOF", f"{100*A6['H3_p_fault_next_given_ok']:.2f}")
mac("HThreeTab", f"{t[0][0]} & {t[0][1]} \\\\ fault & {t[1][0]} & {t[1][1]}")
e1 = EX["E1_H3_rounds_1_to_7"]
mac("SensFF", f"{100*e1['p_fault_next_given_fault']:.1f}"); mac("SensOF", f"{100*e1['p_fault_next_given_ok']:.2f}")
mac("NoiseWithin", f"{100*A6['noise_floor_within_round_range_median']:.2f}")
mac("NoiseBetween", f"{100*A6['between_round_abs_change_median_flagged']:.2f}")
rows = []
for b in B:
    d = A7["devices"][b]
    for q, v in d["per_qubit"].items():
        mu, nb = v["D_mux"], v["D_nbr"]
        rows.append(f"{nm(b)} & q{q} & {v['role']} & {100*d['selection']['e_probe'][q]:.1f} & {100*d['selection']['e_ibm'][q]:.1f} & "
                    f"{100*v['e']['ISO']:.1f} & {100*v['e']['ALL']:.1f} & {100*v['e']['FLIP']:.1f} & "
                    f"{100*mu['mean']:+.2f} [{100*mu['ci95'][0]:+.2f}, {100*mu['ci95'][1]:+.2f}] & "
                    f"{100*nb['mean']:+.2f} [{100*nb['ci95'][0]:+.2f}, {100*nb['ci95'][1]:+.2f}]\\\\")
    rows.append("\\addlinespace")
mac("ROSevenRows", "\n".join(rows[:-1]))
mx = max(abs(v[k]["mean"]) for d in A7["devices"].values() for v in d["per_qubit"].values() for k in ("D_mux", "D_nbr"))
mac("MaxD", f"{100*mx:.2f}")
mac("ROSevenJobs", ", ".join(f"\\texttt{{{A7['devices'][b]['job_id']}}}" for b in B))
cad = EX["E2_ibm_update_cadence"]
rows = [f"{nm(b)} & {' '.join(str(x) for x in cad[b]['qubits_changed'])}\\\\" for b in B]
mac("CadRows", "\n".join(rows))
e3 = EX["E3_update_alignment"]["ibm_fez"]
mac("AlignRows", "\n".join(f"{r['round']} & {r['time'][5:16].replace('T', ' ')} & {r['rho']:.3f} & {100*r['median_abs_gap']:.2f}\\\\" for r in e3["new_vs_round"]))
mac("OldRho", f"{e3['old_vs_last_round']['rho']:.3f}"); mac("OldGap", f"{100*e3['old_vs_last_round']['median_abs_gap']:.2f}")
U = json.loads((ROOT / "docs/phase7/ro06_07_job_usage.json").read_text())
mac("TotalSeconds", int(U["total_s"])); mac("NJobs", len(U["jobs"]))
(HERE / "generated.tex").write_text("\n".join(o) + "\n")
print("\n".join(o)[:3000])
