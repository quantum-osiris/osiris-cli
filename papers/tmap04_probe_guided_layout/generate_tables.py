#!/usr/bin/env python3
"""LaTeX tables for the TESSERACT-MAP-04 paper, read from docs/phase4/ (no hand-typed results)."""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
P4 = ROOT / "docs" / "phase4"
BACKENDS = ["ibm_marrakesh", "ibm_fez", "ibm_kingston"]
ARMS = [("B1_PROBE_BEST", "B1 probe best"), ("B2_CAL_BEST", "B2 calibration best"), ("B3_STOCK", "B3 stock level 3"), ("B4_PROBE_MED", "B4 probe median")]
CON = [("L1_probe_vs_calibration_path", "L1", "B1$-$B2"), ("L2_probe_vs_stock_layout", "L2", "B1$-$B3"),
       ("L3_probe_best_vs_probe_median", "L3", "B1$-$B4"), ("L4_L1_after_readout_mitigation", "L4", "(B1$-$B2)$_{\\rm mit}$")]


def j(b: str, w: str):
    return json.loads((P4 / f"tesseract_map_04_{b}_{w}").read_text())


def sci(p: float) -> str:
    if p >= 0.01:
        return f"{p:.2f}"
    m, e = f"{p:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


def main() -> None:
    out = ["% Generated by generate_tables.py -- do not edit by hand."]
    arm_rows, con_rows, job_rows = [], [], []
    total = 0
    helps = 0
    for b in BACKENDS:
        A = j(b, "live_analysis.json")
        L = j(b, "live_prereg_lock.json")
        cal = j(b, "probe_time_calibration.json")
        probe = j(b, "probe_readout.json")["mean_assign_err"]
        pr = j(b, "probe_raw_counts.json")
        bn = b.replace("_", "\\_")
        for i, (k, lab) in enumerate(ARMS):
            a = A["arms"][k]
            lay = L["arm_manifests"][k]["final_physical_layout"]
            wq = max(lay, key=lambda q: float(probe[str(q)]))
            ibm = cal["qubits"][str(wq)]["readout_error"]
            arm_rows.append(f"{bn if i == 0 else ''} & {lab} & {a['mean_fcl_raw']:.4f} ({a['sd_fcl_raw']:.4f}) & {a['mean_fcl_mit']:.3f} & "
                            f"q{wq}: {100*float(probe[str(wq)]):.1f} / {100*ibm:.1f}\\\\")
        arm_rows.append("\\addlinespace")
        for i, (k, lid, form) in enumerate(CON):
            c = A["contrasts"][k]
            lo, hi = c["ci95_pp"]
            con_rows.append(f"{bn if i == 0 else ''} & {lid} & {form} & {c['mean_pp']:+.2f} & [{lo:+.2f}, {hi:+.2f}] & {sci(c['p_holm'])} & {sci(c['wilcoxon_p_holm'])}\\\\")
        con_rows.append("\\addlinespace")
        c1 = A["contrasts"]["L1_probe_vs_calibration_path"]
        helps += int(c1["mean_pp"] > 0 and c1["p_holm"] < 0.05)
        u = int(pr["job_usage_seconds"]) + int(A["job_usage_seconds"])
        total += u
        job_rows.append(f"{bn} & \\texttt{{{pr['job_id']}}} & \\texttt{{{A['job_id']}}} & {u}\\\\")
    out.append("\\newcommand{\\ArmRows}{" + "\n".join(arm_rows[:-1]) + "}")
    out.append("\\newcommand{\\ContrastRows}{" + "\n".join(con_rows[:-1]) + "}")
    out.append("\\newcommand{\\JobRows}{" + "\n".join(job_rows) + "}")
    out.append(f"\\newcommand{{\\TotalSeconds}}{{{total}}}")
    out.append(f"\\newcommand{{\\HelpsCount}}{{{helps}}}")
    (HERE / "generated.tex").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
